def make_charts() -> None:
    ASSETS.mkdir(parents=True, exist_ok=True)
    font_file = THAI_FONT_FILE if THAI_FONT_FILE.exists() else Path(r"C:\Windows\Fonts\angsana.ttc")
    title_font = ImageFont.truetype(str(font_file), 42)
    label_font = ImageFont.truetype(str(font_file), 27)
    small_font = ImageFont.truetype(str(font_file), 23)

    image = Image.new("RGB", (1600, 960), "white")
    draw = ImageDraw.Draw(image)
    draw.text((800, 38), "การกระจายจำนวนคลิปของชุดข้อมูล HandVox", font=title_font, anchor="ma", fill="#1F1F1F")
    left, top, bar_height, gap, max_width = 245, 105, 34, 15, 1130
    for index, (name, value) in enumerate(LABEL_COUNTS):
        y = top + index * (bar_height + gap)
        draw.text((left - 18, y + bar_height / 2), name, font=label_font, anchor="rm", fill="#1F1F1F")
        draw.rectangle((left, y, left + max_width, y + bar_height), fill="#F2F2F2", outline="#D9D9D9")
        width = max_width * value / 30
        draw.rectangle((left, y, left + width, y + bar_height), fill="#4C86B6", outline="#2F5D7C")
        draw.text((left + width + 12, y + bar_height / 2), str(value), font=small_font, anchor="lm", fill="#1F1F1F")
    draw.text((800, 915), "จำนวนคลิปต่อคำ (ค่าสูงสุด 30 คลิป)", font=label_font, anchor="mm", fill="#1F1F1F")
    image.save(DATASET_FIGURE, quality=95)

    metric_names = ["Accuracy", "Macro Precision", "Macro Recall", "Macro F1", "Weighted F1"]
    metric_values = [94.29, 93.75, 93.75, 93.75, 94.29]
    colors = ["#2E75B6", "#70AD47", "#70AD47", "#ED7D31", "#2E75B6"]
    image = Image.new("RGB", (1500, 760), "white")
    draw = ImageDraw.Draw(image)
    draw.text((750, 45), "ผลการประเมินแบบจำลอง HandVox", font=title_font, anchor="ma", fill="#1F1F1F")
    left, top, bar_height, gap, max_width = 330, 150, 62, 45, 1010
    for index, (name, value, color) in enumerate(zip(metric_names, metric_values, colors)):
        y = top + index * (bar_height + gap)
        draw.text((left - 22, y + bar_height / 2), name, font=label_font, anchor="rm", fill="#1F1F1F")
        draw.rectangle((left, y, left + max_width, y + bar_height), fill="#F2F2F2", outline="#D9D9D9")
        width = max_width * value / 100
        draw.rectangle((left, y, left + width, y + bar_height), fill=color, outline="#595959")
        draw.text((left + width - 12, y + bar_height / 2), f"{value:.2f}%", font=label_font, anchor="rm", fill="white")
    draw.text((840, 706), "ค่าตัวชี้วัด (ร้อยละ)", font=label_font, anchor="mm", fill="#1F1F1F")
    image.save(SUMMARY_FIGURE, quality=95)


def add_reference_heading_style(doc: Document) -> None:
    """Match the supplied form: title 20 pt; numbered headings/body 16 pt."""
    for style_name in ("Heading 1", "Heading 2"):
        style = doc.styles[style_name]
        style.font.name = FONT_NAME
        style.font.size = Pt(16)
        style.font.bold = True
        style.font.color.rgb = None
        style.paragraph_format.left_indent = Cm(0)
        style.paragraph_format.first_line_indent = Cm(0)
        style.paragraph_format.space_before = Pt(8)
        style.paragraph_format.space_after = Pt(2)

    for paragraph in doc.paragraphs:
        if paragraph.style.name in {"Heading 1", "Heading 2"}:
            paragraph.paragraph_format.left_indent = Cm(0)
            paragraph.paragraph_format.first_line_indent = Cm(0)
            for run in paragraph.runs:
                set_run_font(run, 16, bold=True, color=INK)


